#!/usr/bin/env python3
"""Writes test/hpack_vectors.h: header blocks and the header lists they decode to, for hpack_test.c.

Usage: uv run --with hpack==4.1.0 python3 tools/hpack_vectors.py rfc7541.txt > test/hpack_vectors.h

Two sources, neither of them ours:
- RFC 7541 Appendix C.3 to C.6: each example's "Header list to encode" and its "Hex dump of encoded data" (C.5 and C.6
  run with a 256-byte table, so they evict).
- Python's hpack library (the encoder of hyper/h2), for what the RFC's examples don't reach: Huffman on every string,
  incremental indexing with eviction at several table sizes, size updates (down, to zero, back up) and never-indexed
  fields. Each block is decoded back with the library's decoder as a check before it is written.
"""
import re
import sys

import hpack

text = open(sys.argv[1]).read()


def examples(section, until):
    body = text[text.index("\n" + section):text.index("\n" + until)]
    blocks = []
    for part in re.split(r"\nC\.\d\.\d\.  [^\n]*\n", body)[1:]:
        lst = part[part.index("Header list to encode:"):part.index("Hex dump of encoded data:")]
        headers = []
        for line in lst.splitlines()[1:]:
            line = line.strip()
            if ": " not in line:  # a blank line, or a page break's header or footer
                continue
            name, value = line[1:].split(": ", 1) if line.startswith(":") else line.split(": ", 1)
            headers.append(((":" if line.startswith(":") else "") + name, value))
        dump = part[part.index("Hex dump of encoded data:"):part.index("Decoding process:")]
        hexs = "".join(l.split("|")[0].replace(" ", "") for l in dump.splitlines()[1:] if "|" in l)
        blocks.append((bytes.fromhex(hexs), headers))
    return blocks


seqs = [
    ("RFC 7541 C.3, requests without Huffman", 4096, examples("C.3.  Request Examples without Huffman Coding", "C.4.  ")),
    ("RFC 7541 C.4, requests with Huffman", 4096, examples("C.4.  Request Examples with Huffman Coding", "C.5.  ")),
    ("RFC 7541 C.5, responses without Huffman, 256-byte table", 256,
     examples("C.5.  Response Examples without Huffman Coding", "C.6.  ")),
    ("RFC 7541 C.6, responses with Huffman, 256-byte table", 256,
     examples("C.6.  Response Examples with Huffman Coding", "Acknowledgments")),
]

# What a Tailscale control server's responses look like, and the edges of the byte range.
HEADERS = [
    [(":status", "200"), ("content-type", "application/json"), ("date", "Thu, 23 Oct 2026 01:02:03 GMT")],
    [(":status", "200"), ("content-type", "application/json"), ("content-length", "1234"),
     ("x-tailscale-request-id", "REQ-20261023002400e624cf46e90ef471")],
    [(":status", "404"), ("content-type", "text/plain; charset=utf-8"), ("x-content-type-options", "nosniff")],
    [(":status", "200"), ("binary", "".join(chr(c) for c in range(1, 256)))],  # every byte value through Huffman
    [(":status", "500"), ("long", "x" * 300), ("content-type", "application/json")],  # bigger than a small table
]


def lib_seq(name, size, huffman, resize=None):
    enc = hpack.Encoder()
    dec = hpack.Decoder()
    blocks = []
    enc.header_table_size = size
    dec.max_allowed_table_size = 4096
    for i, h in enumerate(HEADERS * 2):
        if resize and i in resize:
            enc.header_table_size = resize[i]
        # As bytes: a str is UTF-8 encoded by the library, and the byte values are the point of the binary field.
        b = enc.encode([(k.encode("latin-1"), v.encode("latin-1")) for k, v in h], huffman=huffman)
        assert [(k.decode("latin-1") if isinstance(k, bytes) else k, v.decode("latin-1") if isinstance(v, bytes) else v)
                for k, v in dec.decode(b, raw=True)] == h
        blocks.append((b, h))
    return (name, 4096, blocks)


seqs.append(lib_seq("hpack 4.1.0, Huffman, 4096-byte table", 4096, True))
seqs.append(lib_seq("hpack 4.1.0, Huffman, size updates to 256, 0, 4096", 4096, True, {0: 256, 3: 0, 5: 4096, 7: 100}))
seqs.append(lib_seq("hpack 4.1.0, plain literals, size update to 64", 4096, False, {0: 64}))
enc = hpack.Encoder()
nb = enc.encode([(":status", "200"), hpack.NeverIndexedHeaderTuple("authorization", "secret")], huffman=True)
seqs.append(("hpack 4.1.0, a never-indexed field", 4096, [(nb, [(":status", "200"), ("authorization", "secret")])]))


def cbytes(b):
    return ", ".join(f"0x{x:02x}" for x in b)


def cstr(s):
    out = ""
    for ch in s.encode("latin-1"):
        # Octal, not \x: a \x escape swallows any hex digit after it. (No field holds a NUL, so strlen works.)
        out += f"\\{ch:03o}" if ch < 0x20 or ch >= 0x7f or ch in (0x22, 0x5c, 0x3f) else chr(ch)
    return '"' + out + '"'


print("// Generated by tools/hpack_vectors.py (RFC 7541 Appendix C and Python's hpack 4.1.0). Don't edit: rerun it.")
print("#include <stddef.h>\n#include <stdint.h>\n")
print("typedef struct { const uint8_t *block; size_t len; const char *const *fields; size_t nfields; } hv_block_t;")
print("typedef struct { const char *name; uint32_t table; const hv_block_t *blocks; size_t nblocks; } hv_seq_t;\n")
for si, (name, size, blocks) in enumerate(seqs):
    for bi, (b, h) in enumerate(blocks):
        print(f"static const uint8_t HV_{si}_{bi}[] = {{{cbytes(b)}}};")
        print(f"static const char *const HF_{si}_{bi}[] = {{" + ", ".join(f"{cstr(k)}, {cstr(v)}" for k, v in h) + "};")
    print(f"static const hv_block_t HB_{si}[] = {{")
    for bi, (b, h) in enumerate(blocks):
        print(f"    {{HV_{si}_{bi}, sizeof HV_{si}_{bi}, HF_{si}_{bi}, {len(h)}}},")
    print("};")
print("static const hv_seq_t HV_SEQS[] = {")
for si, (name, size, blocks) in enumerate(seqs):
    print(f"    {{{cstr(name)}, {size}, HB_{si}, {len(blocks)}}},")
print("};")

#!/usr/bin/env python3
"""Writes src/hpack_tables.h from RFC 7541's own text: Appendix A (the static table) and Appendix B (the Huffman code).

Usage: python3 tools/hpack_tables.py rfc7541.txt > src/hpack_tables.h
(the RFC is https://www.rfc-editor.org/rfc/rfc7541.txt). It checks what the decoder relies on: 61 static entries, 257
Huffman codes whose bit and hex columns agree, and that the code is canonical (sorted by length, each code the previous
plus one, shifted at each new length), so a count per length and the symbols in code order decode it.
"""
import re
import sys

text = open(sys.argv[1]).read()
appendix_a = text[text.index("\nAppendix A.  Static Table Definition"):text.index("\nAppendix B.  Huffman Code")]
appendix_b = text[text.index("\nAppendix B.  Huffman Code"):text.index("\nAppendix C.  Examples")]

static = []
for m in re.finditer(r"^\s+\| (\d+)\s+\| (\S+)\s+\| (.*?)\s*\|$", appendix_a, re.M):
    static.append((int(m.group(1)), m.group(2), m.group(3)))
assert [i for i, _, _ in static] == list(range(1, 62)), "static table: expected entries 1 to 61"

codes = []
for m in re.finditer(r"^\s+(?:'.' |EOS )?\(\s*(\d+)\)\s+\|([01|]+)\s+([0-9a-f]+)\s+\[\s*(\d+)\]$", appendix_b, re.M):
    sym, bits, hexv, n = int(m.group(1)), m.group(2).replace("|", ""), int(m.group(3), 16), int(m.group(4))
    assert len(bits) == n and int(bits, 2) == hexv, f"symbol {sym}: bits and hex disagree"
    codes.append((sym, hexv, n))
assert [s for s, _, _ in codes] == list(range(257)), "huffman: expected symbols 0 to 256"

order = sorted(codes, key=lambda c: (c[2], c[1]))
code, length = order[0][1], order[0][2]
assert code == 0
for prev, cur in zip(order, order[1:]):
    expect = (prev[1] + 1) << (cur[2] - prev[2])
    assert cur[1] == expect, f"not canonical at symbol {cur[0]}"
count = [0] * 31
for _, _, n in codes:
    count[n] += 1


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


out = []
out.append("#pragma once")
out.append("// Generated by tools/hpack_tables.py from RFC 7541 (Appendix A, the static table; Appendix B, the Huffman code).")
out.append("// Don't edit: rerun the script.")
out.append("#include <stdint.h>")
out.append("")
out.append("static const char *const HPACK_STATIC[61][2] = {")
for _, name, value in static:
    out.append(f"    {{{cstr(name)}, {cstr(value)}}},")
out.append("};")
out.append("")
out.append("// The canonical Huffman code: how many codes have each length (1 to 30 bits), then the symbols in code order.")
out.append("static const uint16_t HPACK_HUFF_COUNT[31] = {" + ", ".join(str(c) for c in count) + "};")
out.append("static const uint16_t HPACK_HUFF_SYMS[257] = {")
syms = [str(s) for s, _, _ in order]
for i in range(0, 257, 16):
    out.append("    " + ", ".join(syms[i:i + 16]) + ",")
out.append("};")
print("\n".join(out))
